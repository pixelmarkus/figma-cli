#!/usr/bin/env node

/**
 * Figma CLI Daemon
 *
 * Supports two modes:
 * - Yolo Mode (CDP): Direct connection via Chrome DevTools Protocol (fast, requires patching)
 * - Safe Mode (Plugin): Connection via Figma plugin WebSocket (secure, no patching)
 *
 * Security features:
 * - Session token authentication (X-Daemon-Token header)
 * - No CORS headers (blocks cross-origin browser requests)
 * - Host header validation (blocks DNS rebinding)
 * - Idle timeout auto-shutdown (configurable, default 10 minutes)
 */

import { createServer } from 'http';
import { WebSocketServer, WebSocket } from 'ws';
import { readFileSync, statSync, writeFileSync, unlinkSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { homedir, tmpdir } from 'os';
import { fileURLToPath, pathToFileURL } from 'url';
import { wrapCodeIfNeeded } from './lib/eval-wrap.js';

const DAEMON_ROOT = dirname(fileURLToPath(import.meta.url));
const DAEMON_VERSION = (() => { try { return JSON.parse(readFileSync(join(DAEMON_ROOT, '..', 'package.json'), 'utf8')).version; } catch { return null; } })();

// Hot-reload FigmaClient: copy to temp file and import (Node.js ES modules don't support cache busting)
const __dirname = dirname(fileURLToPath(import.meta.url));
const figmaClientPath = join(__dirname, 'figma-client.js');
let FigmaClient = null;
let lastModTime = 0;
let lastTempFile = null;

async function getFigmaClient() {
  try {
    const stat = statSync(figmaClientPath);
    const modTime = stat.mtimeMs;

    // Reload if file changed or never loaded
    if (!FigmaClient || modTime > lastModTime) {
      // Clean up old temp files in project directory (keeps node_modules accessible)
      try {
        const oldFiles = readdirSync(__dirname).filter(f => f.startsWith('.figma-client-') && f.endsWith('.mjs'));
        for (const f of oldFiles) {
          try { unlinkSync(join(__dirname, f)); } catch {}
        }
      } catch {}

      // Copy to temp file in same directory (so imports resolve correctly)
      const tempFile = join(__dirname, `.figma-client-${modTime}.mjs`);
      const content = readFileSync(figmaClientPath, 'utf8');
      writeFileSync(tempFile, content);
      lastTempFile = tempFile;

      // Import from temp file
      const tempUrl = pathToFileURL(tempFile).href;
      const module = await import(tempUrl);
      FigmaClient = module.FigmaClient;

      const wasReload = lastModTime > 0;
      lastModTime = modTime;
      if (wasReload) console.log('[daemon] Hot-reloaded figma-client.js');
    }
  } catch (e) {
    console.error('[daemon] Hot-reload error:', e.message);
    // Fallback: just import normally
    if (!FigmaClient) {
      const module = await import('./figma-client.js');
      FigmaClient = module.FigmaClient;
    }
  }
  return FigmaClient;
}

const PORT = parseInt(process.env.DAEMON_PORT) || 3456;
const MODE = process.env.DAEMON_MODE || 'auto'; // 'auto', 'cdp', 'plugin'
const IDLE_TIMEOUT_MS = parseInt(process.env.DAEMON_IDLE_TIMEOUT) || 60 * 60 * 1000; // Default: 60 minutes (long interactive design sessions have quiet stretches; the CLI also auto-restarts the daemon if it ever does shut down)

// ============ SECURITY ============

// Load session token (generated by CLI on daemon start)
const TOKEN_FILE = join(homedir(), '.figma-ds-cli', '.daemon-token');
// This daemon owns the singleton PID file ONLY once it wins the port bind (see
// httpServer.listen below). The CLI no longer writes it, so the file always
// points at the daemon actually serving on the port — never a crashed loser.
const PID_FILE = join(homedir(), '.figma-cli-daemon.pid');
let SESSION_TOKEN = null;

try {
  SESSION_TOKEN = readFileSync(TOKEN_FILE, 'utf8').trim();
  console.log('[daemon] Session token loaded');
} catch {
  console.error('[daemon] WARNING: No session token found. Daemon will reject all requests.');
}

/**
 * Validate request authentication and origin
 * Returns null if valid, or an error string if rejected
 */
function validateRequest(req) {
  // Layer 1: Host header validation (blocks DNS rebinding)
  const host = req.headers.host || '';
  if (!host.match(/^(localhost|127\.0\.0\.1)(:\d+)?$/)) {
    return 'Invalid host header';
  }

  // Layer 2: Session token (blocks unauthorized local processes)
  const token = req.headers['x-daemon-token'];
  if (!SESSION_TOKEN) {
    return 'No session token configured';
  }
  if (token !== SESSION_TOKEN) {
    return 'Invalid or missing token';
  }

  return null; // Valid
}

// ============ IDLE TIMEOUT ============

let lastActivityTime = Date.now();
let idleTimer = null;

function resetIdleTimer() {
  lastActivityTime = Date.now();
  if (idleTimer) clearTimeout(idleTimer);
  idleTimer = setTimeout(() => {
    const idleSecs = Math.round((Date.now() - lastActivityTime) / 1000);
    console.log(`[daemon] Idle for ${idleSecs}s — auto-shutting down`);
    shutdown();
  }, IDLE_TIMEOUT_MS);
}

// Start the idle timer immediately
resetIdleTimer()

// Several agents can work on several open files at once. Each request names
// its file (the CLI's FIGMA_FILE, a substring of the file name); the daemon
// keeps one connection per file instead of one for the whole daemon. Before,
// a request for another file restarted the daemon, which killed whatever the
// other agents had in flight.
const DEFAULT_FILE = (process.env.FIGMA_FILE || '').trim();
const fileKey = (file) => String(file || DEFAULT_FILE || '').trim().toLowerCase();
const matchesFile = (name, file) => !!name && name.toLowerCase().includes(fileKey(file));

// CDP Clients (Yolo Mode), keyed by fileKey ('' = Figma's first design tab)
const cdpClients = new Map();
const cdpConnecting = new Map(); // fileKey -> Promise<FigmaClient>
const cdpHealth = new Map(); // fileKey -> { time, ok }
const HEALTH_CACHE_MS = 30000; // Cache health for 30 seconds (reduces overhead)

// Plugin connections (Safe Mode): one per file running the FigCli plugin
const pluginConns = new Set(); // { ws, file, fileLookup }
let pluginPendingRequests = new Map();
let pluginMsgId = 0;

// ============ CDP MODE (YOLO) ============

const isOpen = (client) => !!(client && client.ws && client.ws.readyState === 1);

async function isCdpHealthy(forceCheck = false, file = null) {
  const key = fileKey(file);
  const client = cdpClients.get(key);
  // Quick WebSocket state check (no network call)
  if (!isOpen(client)) return false;

  // Use cached result if recent (avoids constant eval calls)
  const now = Date.now();
  const cached = cdpHealth.get(key);
  if (!forceCheck && cached && now - cached.time < HEALTH_CACHE_MS) {
    return cached.ok;
  }

  let ok = false;
  try {
    const result = await Promise.race([
      // Checks the Plugin API, not just the socket: after a file reload the
      // socket is fine but the bound context has no `figma` any more.
      client.eval('typeof figma === "object" && figma !== null && !!figma.root ? 1 : 0'),
      new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), 2000))
    ]);
    ok = result === 1;
  } catch {}
  cdpHealth.set(key, { time: now, ok });
  return ok;
}

function dropCdpClient(file) {
  const key = fileKey(file);
  const client = cdpClients.get(key);
  if (client) { try { client.close(); } catch {} }
  cdpClients.delete(key);
  cdpHealth.delete(key);
}

async function getCdpClient(file = null) {
  const key = fileKey(file);
  // Fast path: if we have a client with open WebSocket, use it
  const existing = cdpClients.get(key);
  if (isOpen(existing)) return existing;

  // WebSocket closed, need to reconnect
  if (existing) {
    console.log(`[daemon] CDP WebSocket closed${key ? ` (${key})` : ''}, reconnecting...`);
    dropCdpClient(file);
  }

  // Share a connection attempt already in progress for the same file
  if (cdpConnecting.has(key)) return cdpConnecting.get(key);

  const attempt = (async () => {
    const ClientClass = await getFigmaClient();
    const client = new ClientClass();
    // The file pins the connection to one open file (substring match on the
    // tab title). Without it Figma's first design tab wins.
    await client.connect(file || DEFAULT_FILE || null);
    cdpClients.set(key, client);
    cdpHealth.set(key, { time: Date.now(), ok: true });
    console.log(`[daemon] Connected to Figma via CDP (Yolo Mode): ${client.pageTitle}`);
    // File warming: Figma loads pages lazily, so the first command that looks
    // beyond the current page waits for every page to load (seconds on a big
    // design system). Start that load now, in the background, so it is done
    // before the first real command arrives. Never awaited, never fatal.
    client.eval('figma.loadAllPagesAsync().then(() => true)').catch(() => {});
    return client;
  })();
  cdpConnecting.set(key, attempt);
  try {
    return await attempt;
  } finally {
    cdpConnecting.delete(key);
  }
}

async function evalViaCdp(code, file = null) {
  const client = await getCdpClient(file);
  return client.eval(code);
}

// ============ PLUGIN MODE (SAFE) ============

function openPlugins() {
  return [...pluginConns].filter(c => c.ws.readyState === WebSocket.OPEN);
}

function isPluginConnected() {
  return openPlugins().length > 0;
}

// Ask a freshly connected plugin which file it runs in. Older plugins do not
// say so in their hello, and every plugin answers an eval.
function lookupPluginFile(conn) {
  if (!conn.fileLookup) {
    conn.fileLookup = Promise.race([
      evalViaPlugin(conn, 'figma.root.name'),
      new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), 3000)),
    ]).then(name => { conn.file = name || null; if (name) seenFiles.add(name.toLowerCase()); }, () => { conn.fileLookup = null; });
  }
  return conn.fileLookup;
}

// The plugin for this file. No file: the most recently connected plugin (the
// old single-connection behaviour). A file nobody's plugin runs in: null.
async function pickPlugin(file) {
  const open = openPlugins();
  if (open.length === 0) return null;
  if (!fileKey(file)) return open[open.length - 1];
  await Promise.all(open.filter(c => !c.file).map(lookupPluginFile));
  return open.reverse().find(c => matchesFile(c.file, file)) || null;
}

async function evalViaPlugin(conn, code, retryCount = 0) {
  if (!conn || conn.ws.readyState !== WebSocket.OPEN) {
    throw new Error('Plugin not connected. Start the Figma CLI Bridge plugin in Figma.');
  }

  return new Promise((resolve, reject) => {
    const id = ++pluginMsgId;
    const timeout = setTimeout(() => {
      pluginPendingRequests.delete(id);
      reject(new Error('Plugin execution timeout (25s)'));
    }, 25000); // 25s timeout to match plugin-side timeout

    pluginPendingRequests.set(id, { resolve, reject, timeout, code, retryCount, conn });

    try {
      conn.ws.send(JSON.stringify({
        action: 'eval',
        id: id,
        code: code
      }));
    } catch (sendError) {
      clearTimeout(timeout);
      pluginPendingRequests.delete(id);
      reject(new Error(`Plugin send error: ${sendError.message}`));
    }
  });
}

// ============ UNIFIED EVAL ============

// Safe Mode: Figma runs the plugin and an export on the same thread. A heavy
// export (seconds to tens of seconds in a big file) starves the plugin and its
// connection drops; it comes back by itself. Say that, instead of falling back
// to a CDP port that is not there and reporting "fetch failed".
let pluginSeen = false;
const seenFiles = new Set(); // lowercased names of files whose plugin has connected
const PLUGIN_GONE = 'Plugin disconnected';
const pluginGone = (file) => new Error(
  `${PLUGIN_GONE}${fileKey(file) ? ` for "${file}"` : ''}: Figma dropped the FigCli plugin while it was busy ` +
  '(a heavy export can take tens of seconds). It reconnects by itself within a few seconds; run the command again. ' +
  'To build context without an export use `figma-cli read <id>`.'
);

const fileNotOpen = (file) => new Error(
  `No connection to a Figma file matching "${file}". Open it in Figma` +
  (MODE === 'plugin' || pluginSeen ? ' and run Plugins → Development → FigCli there.' : '.')
);

async function executeEval(code, file = null) {
  // Plugin first (auto and plugin mode), handles its own wrapping
  if (MODE !== 'cdp') {
    const plugin = await pickPlugin(file);
    if (plugin) return evalViaPlugin(plugin, code);
    if (MODE === 'plugin') {
      if (fileKey(file) && isPluginConnected()) throw fileNotOpen(file);
      throw new Error('Plugin not connected. Start the Figma CLI Bridge plugin in Figma.');
    }
  }
  // CDP needs wrapping for top-level return statements
  try {
    return await evalViaCdp(wrapCodeIfNeeded(code), file);
  } catch (e) {
    if (fileKey(file) && /No Figma design file open/.test(e.message)) throw fileNotOpen(file);
    // No CDP here: a Safe Mode setup. "Gone" only for a file whose plugin was
    // here before; a pin that never matched anything is a file not open.
    if (pluginSeen && /fetch failed|ECONNREFUSED/.test(e.message)) {
      const key = fileKey(file);
      if (key && ![...seenFiles].some(f => f.includes(key))) throw fileNotOpen(file);
      throw pluginGone(file);
    }
    throw e;
  }
}

function getMode() {
  if (MODE === 'plugin') return 'safe';
  if (MODE === 'cdp') return 'yolo';
  // Auto: return what's actually connected
  if (isPluginConnected()) return 'safe';
  if (cdpClients.size > 0) return 'yolo';
  return 'disconnected';
}

/** Names of every file this daemon can reach right now. */
function connectedFiles() {
  const names = openPlugins().map(c => c.file).filter(Boolean);
  for (const c of cdpClients.values()) if (isOpen(c) && c.pageTitle) names.push(c.pageTitle);
  return [...new Set(names)];
}

// ============ HTTP SERVER ============

async function handleRequest(req, res) {
  // Reset idle timer on every request
  resetIdleTimer();

  // SECURITY: No CORS headers (blocks all cross-origin browser requests)

  // Block preflight requests (browsers send OPTIONS before cross-origin POST)
  if (req.method === 'OPTIONS') {
    res.writeHead(403, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'CORS preflight rejected' }));
    return;
  }

  // SECURITY: Validate authentication on all routes
  const authError = validateRequest(req);
  if (authError) {
    res.writeHead(403, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Unauthorized: ' + authError }));
    return;
  }

  // Health check
  if (req.url === '/health') {
    const mode = getMode();
    const pluginConnected = isPluginConnected();
    const cdpHealthy = await isCdpHealthy();
    const defaultCdp = cdpClients.get(fileKey(null));
    const latestPlugin = openPlugins().pop();

    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      status: (pluginConnected || cdpHealthy) ? 'ok' : 'disconnected',
      mode: mode,
      plugin: pluginConnected,
      cdp: cdpHealthy,
      // Which open file this daemon is bound to. The CLI compares it against
      // FIGMA_FILE and rebinds when they diverge — otherwise commands silently
      // hit whichever file happened to be first when the daemon started.
      file: (defaultCdp && defaultCdp.pageTitle) || (latestPlugin && latestPlugin.file) || null,
      // Every file reachable right now. multiFile tells the CLI that a request
      // for another file is routed by its `file` field, so FIGMA_FILE no longer
      // needs a daemon restart (which killed other agents' requests).
      files: connectedFiles(),
      multiFile: true,
      // Which figma-cli code this daemon runs. After an update the old daemon
      // would keep serving render-batch and eval with old code until it idles
      // out; the CLI restarts it when these do not match its own.
      version: DAEMON_VERSION,
      root: DAEMON_ROOT,
      idleTimeoutMs: IDLE_TIMEOUT_MS
    }));
    return;
  }

  // Force reconnect (CDP only). ?file= reconnects that file's connection.
  if (req.url === '/reconnect' || req.url.startsWith('/reconnect?')) {
    try {
      const file = new URL(req.url, 'http://localhost').searchParams.get('file');
      dropCdpClient(file);
      await getCdpClient(file);
      res.writeHead(200, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ status: 'reconnected', mode: 'yolo' }));
    } catch (error) {
      res.writeHead(500, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: error.message }));
    }
    return;
  }

  // Execute command
  if (req.url === '/exec' && req.method === 'POST') {
    let body = '';
    req.on('data', chunk => body += chunk);
    req.on('end', async () => {
      const MAX_RETRIES = 2;
      let lastError;

      // Parse once, outside the retry loop — a malformed body never becomes
      // valid by retrying, and retries used to tear down a healthy CDP
      // connection for it.
      let payload;
      try {
        payload = JSON.parse(body);
      } catch (e) {
        res.writeHead(400, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: 'Invalid JSON body: ' + e.message }));
        return;
      }

      for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
        try {
          const { action, code, jsx, jsxArray, gap, vertical, collection, file } = payload;
          let result;

          const execWithTimeout = async (fn, timeoutMs = 30000) => {
            return Promise.race([
              fn(),
              new Promise((_, reject) =>
                setTimeout(() => reject(new Error(`Execution timeout (${timeoutMs/1000}s)`)), timeoutMs)
              )
            ]);
          };

          switch (action) {
            case 'eval':
              result = await execWithTimeout(() => executeEval(code, file));
              break;
            case 'render': {
              // Parse JSX to code, then execute via unified eval (works with both CDP and Plugin)
              const ClientClass = await getFigmaClient();
              const parser = new ClientClass();
              const renderCode = await parser.parseJSX(jsx, { page: payload.page || null });
              result = await execWithTimeout(() => executeEval(renderCode, file), 90000); // 90s for renders with icons
              break;
            }
            case 'render-batch': {
              // Single eval for ALL frames (10x faster than loop)
              const ClientClass = await getFigmaClient();
              const batchParser = new ClientClass();
              if (collection) batchParser.setCollection(collection);
              const batchCode = await batchParser.parseJSXBatch(jsxArray, {
                gap: gap || 40,
                vertical: vertical || false,
                page: payload.page || null
              });
              result = await execWithTimeout(() => executeEval(batchCode, file), 60000); // 60s for batches
              break;
            }
            default:
              throw new Error(`Unknown action: ${action}`);
          }

          res.writeHead(200, { 'Content-Type': 'application/json' });
          res.end(JSON.stringify({ result, mode: getMode() }));
          return;
        } catch (error) {
          lastError = error;
          console.log(`[daemon] Attempt ${attempt + 1} failed: ${error.message}`);

          // The plugin went away while running this request: it may already
          // have changed the file, so running it again could do it twice.
          if (error.message.startsWith(PLUGIN_GONE)) break;

          // NEVER retry a mutating render: executeEval may have already created
          // the frame before the response errored (a transient CDP hiccup under
          // load, e.g. several heavy files open). Retrying re-runs the render
          // code and silently produces a DUPLICATE frame. Fail fast instead —
          // a clear error beats a phantom copy. (Reads/eval may still retry.)
          if (payload.action === 'render' || payload.action === 'render-batch') break;

          // For Safe Mode: wait briefly for potential reconnect
          if (attempt < MAX_RETRIES && MODE === 'plugin') {
            console.log('[daemon] Safe Mode: waiting for plugin reconnect...');
            // Wait up to 2s for plugin to reconnect
            for (let i = 0; i < 10; i++) {
              await new Promise(r => setTimeout(r, 200));
              if (isPluginConnected()) {
                console.log('[daemon] Plugin reconnected, retrying...');
                break;
              }
            }
          }

          // For Yolo Mode: only reconnect when the connection is actually
          // broken. If CDP is healthy, the error came from the executed code
          // itself — retrying would just re-run it (and a timed-out render
          // would create duplicate nodes).
          if (attempt < MAX_RETRIES && MODE !== 'plugin' && !isPluginConnected()) {
            if (await isCdpHealthy(true, payload.file)) {
              console.log('[daemon] CDP healthy — error is not connection-related, not retrying');
              break;
            }
            console.log('[daemon] Reconnecting CDP before retry...');
            // Don't tear down a connection another request is currently building
            if (!cdpConnecting.has(fileKey(payload.file))) dropCdpClient(payload.file);
            // Backoff: 300ms after first failure, 1s after second
            await new Promise(r => setTimeout(r, attempt === 0 ? 300 : 1000));
            try {
              await getCdpClient(payload.file);
              if (!(await isCdpHealthy(true, payload.file))) {
                console.log('[daemon] CDP still unhealthy after reconnect');
              }
            } catch (reconnectError) {
              console.log('[daemon] CDP reconnect failed: ' + reconnectError.message);
            }
          }
        }
      }

      res.writeHead(500, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify({ error: (lastError && lastError.message) || 'Execution failed' }));
    });
    return;
  }

  res.writeHead(404);
  res.end('Not found');
}

// ============ START SERVERS ============

const httpServer = createServer(handleRequest);

// WebSocket server for plugin connections
const wss = new WebSocketServer({ server: httpServer, path: '/plugin' });

wss.on('connection', (ws) => {
  console.log('[daemon] Plugin connected (Safe Mode)');
  const conn = { ws, file: null, fileLookup: null };
  pluginConns.add(conn);
  pluginSeen = true;
  resetIdleTimer(); // Plugin connection counts as activity

  ws.on('message', (data) => {
    resetIdleTimer(); // Plugin messages count as activity
    try {
      const msg = JSON.parse(data.toString());

      if (msg.type === 'hello') {
        console.log(`[daemon] Plugin version: ${msg.version}`);
        lookupPluginFile(conn).then(() => { if (conn.file) console.log(`[daemon] Plugin file: ${conn.file}`); });
      }

      if (msg.type === 'result') {
        const pending = pluginPendingRequests.get(msg.id);
        if (pending) {
          clearTimeout(pending.timeout);
          pluginPendingRequests.delete(msg.id);

          if (msg.error) {
            pending.reject(new Error(msg.error));
          } else {
            pending.resolve(msg.result);
          }
        }
      }

      // Batch result from plugin
      if (msg.type === 'batch-result') {
        const pending = pluginPendingRequests.get(msg.id);
        if (pending) {
          clearTimeout(pending.timeout);
          pluginPendingRequests.delete(msg.id);
          pending.resolve(msg.results);
        }
      }

      // Keepalive ping from plugin
      if (msg.type === 'ping') {
        ws.send(JSON.stringify({ type: 'pong' }));
      }

      if (msg.type === 'pong') {
        // Health check response
      }
    } catch (e) {
      console.error('[daemon] Plugin message error:', e);
    }
  });

  ws.on('close', () => {
    console.log(`[daemon] Plugin disconnected${conn.file ? ` (${conn.file})` : ''}`);
    pluginConns.delete(conn);

    // Reject the requests this plugin had, not other files' requests
    for (const [id, pending] of pluginPendingRequests) {
      if (pending.conn !== conn) continue;
      clearTimeout(pending.timeout);
      pending.reject(pluginGone(conn.file));
      pluginPendingRequests.delete(id);
    }
  });

  ws.on('error', (error) => {
    console.error('[daemon] Plugin WebSocket error:', error.message);
  });
});

// Singleton guard: a second daemon spawned by a concurrent CLI invocation
// (startDaemon has a check-then-act race) will fail to bind the port. Exit it
// cleanly BEFORE it does any work, and do NOT let it touch the PID file — so the
// winner stays the one true daemon. Without this the loser used to crash on an
// unhandled 'error' while the CLI had already written ITS pid to the PID file,
// so isDaemonRunning() saw a dead pid and respawned endlessly (daemon churn →
// non-deterministic double execution).
httpServer.on('error', (err) => {
  if (err && err.code === 'EADDRINUSE') {
    console.log(`[daemon] Port ${PORT} already owned by another daemon — exiting (singleton).`);
    process.exit(0);
  }
  console.error('[daemon] server error:', err);
  process.exit(1);
});

httpServer.listen(PORT, '127.0.0.1', () => {
  // We won the bind: claim the singleton PID file.
  try { writeFileSync(PID_FILE, String(process.pid)); } catch {}
  console.log(`[daemon] Figma CLI daemon running on port ${PORT} (pid ${process.pid})`);
  console.log(`[daemon] Mode: ${MODE === 'auto' ? 'auto (plugin preferred, CDP fallback)' : MODE}`);
  console.log(`[daemon] Idle timeout: ${IDLE_TIMEOUT_MS / 1000}s`);
  console.log(`[daemon] Auth: token required`);
});

// Graceful shutdown
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);

function shutdown() {
  console.log('[daemon] Shutting down...');
  if (idleTimer) clearTimeout(idleTimer);
  for (const client of cdpClients.values()) { try { client.close(); } catch {} }
  for (const conn of pluginConns) { try { conn.ws.close(); } catch {} }
  httpServer.close(() => process.exit(0));
  // Force exit after 3 seconds if graceful shutdown hangs
  setTimeout(() => process.exit(0), 3000);
}

